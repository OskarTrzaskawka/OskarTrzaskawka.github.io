#!/usr/bin/env node
/**
 * Scaffold a new persona from one of the demo personas.
 *
 *   npm run new-persona -- <id> [template]
 *   npm run new-persona -- jane designer
 *
 * Creates src/personas/<id>.ts and .env.<id>, then run: npx vite --mode <id>
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const TEMPLATES = ['developer', 'designer', 'photographer', 'minimal']
const [id, template = 'developer'] = process.argv.slice(2)
const root = resolve(import.meta.dirname, '..')

const fail = (msg) => {
  console.error(`\n  ✗ ${msg}\n\n  Usage: npm run new-persona -- <id> [${TEMPLATES.join('|')}]\n`)
  process.exit(1)
}

if (!id) fail('Missing persona id.')
if (!/^[a-z][a-z0-9-]*$/.test(id)) fail('Persona id must be lowercase letters, numbers and dashes, starting with a letter.')
if (!TEMPLATES.includes(template)) fail(`Unknown template "${template}".`)

const target = resolve(root, 'src/personas', `${id}.ts`)
if (existsSync(target)) fail(`src/personas/${id}.ts already exists.`)

const source = readFileSync(resolve(root, 'src/personas', `${template}.ts`), 'utf8')
const label = id.replace(/(^|-)(\w)/g, (_, dash, c) => (dash ? ' ' : '') + c.toUpperCase())
const result = source
  .replace(/id: '[^']+'/, `id: '${id}'`)
  .replace(/label: '[^']+'/, `label: '${label}'`)
  .replace(/\/\*\*[\s\S]*?\*\/\n(export default)/, `/** ${label} — generated by \`npm run new-persona\`. Edit freely. */\n$1`)

writeFileSync(target, result)
writeFileSync(resolve(root, `.env.${id}`), `# Used by: npx vite --mode ${id}\nVITE_PERSONA=${id}\n`)

console.log(`
  ✓ Created src/personas/${id}.ts  (based on the "${template}" demo)
  ✓ Created .env.${id}

  Next steps:
    1. Edit src/personas/${id}.ts with your own data
    2. npx vite --mode ${id}        # preview it
    3. Set VITE_PERSONA=${id} in .env to make it the default
`)
